# These are the starter notebook's fixed grouping labels, not a live industry taxonomy.
_ASSIGNMENT_GROUPS = (
    ("mega-cap-tech", 10),
    ("semiconductors", 8),
    ("other-tech", 8),
    ("finance", 10),
    ("healthcare", 10),
    ("consumer-staples", 6),
    ("consumer-discretionary", 8),
    ("energy", 6),
    ("industrials", 8),
    ("materials", 6),
    ("real-estate", 5),
    ("communication", 5),
    ("utilities", 1),
    ("broad-etfs", 4),
    ("sector-etfs", 5),
)


def assignment_sector_map(universe):
    groups, offset = {}, 0
    for group, count in _ASSIGNMENT_GROUPS:
        groups.update((s, group) for s in BASELINE_UNIVERSE[offset : offset + count])
        offset += count
    return tuple((symbol, groups.get(symbol, "unknown")) for symbol in universe)
